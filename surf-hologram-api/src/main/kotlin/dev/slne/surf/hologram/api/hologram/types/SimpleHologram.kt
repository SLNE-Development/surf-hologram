package dev.slne.surf.hologram.api.hologram.types

import dev.slne.surf.hologram.api.hologram.Hologram

/**
 * Represents a simple hologram with a static appearance and behavior.
 *
 * A simple hologram is an implementation of the `Hologram` interface without
 * additional dynamic behavior or interactions, making it suitable for
 * straightforward use cases like displaying fixed text or information in the
 * specified location.
 *
 * This interface does not define any extensions or modifications to the base
 * `Hologram` functionality, ensuring simple and lightweight hologram
 * implementations.
 */
interface SimpleHologram : Hologram